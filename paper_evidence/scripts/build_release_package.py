#!/usr/bin/env python3
"""Build a compact, hash-audited, Overleaf-friendly evidence package.

The candidate registry is separate from the selection file. A human changes
only the selection file, then reruns this script with a new release ID.
Existing releases are never overwritten.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
REGISTRY = REPO_ROOT / "paper_evidence/candidates/FIGURE_CANDIDATES.tsv"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_tsv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def latex_text(value: str) -> str:
    """Escape the small set of characters that commonly break LaTeX text."""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(char, char) for char in value)


def copy_artifact(source: Path, destination: Path, release_root: Path) -> dict[str, str]:
    if not source.is_file():
        raise FileNotFoundError(source)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)
    return {
        "source": str(source.relative_to(REPO_ROOT)),
        "release_path": str(destination.relative_to(release_root)),
        "sha256": sha256(destination),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--release-id", required=True)
    parser.add_argument("--selection", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    out = args.out if args.out.is_absolute() else REPO_ROOT / args.out
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"Refusing to overwrite non-empty release: {out}")
    out.mkdir(parents=True, exist_ok=True)

    registry = {row["candidate_id"]: row for row in read_tsv(REGISTRY)}
    selection_path = args.selection if args.selection.is_absolute() else REPO_ROOT / args.selection
    selected_rows = [
        row for row in read_tsv(selection_path)
        if row.get("selected", "").lower() in {"yes", "true", "1"}
    ]
    if not selected_rows:
        raise SystemExit("No candidates selected; edit release_selection.tsv first.")

    artifacts: list[dict[str, str]] = []
    candidates: list[dict[str, str]] = []
    for selection in selected_rows:
        candidate_id = selection["candidate_id"]
        if candidate_id not in registry:
            raise SystemExit(f"Selection is not in registry: {candidate_id}")
        row = registry[candidate_id]
        candidates.append({
            "candidate_id": candidate_id,
            "version": row["version"],
            "status": row["status"],
            "title": row["title"],
            "manual_notes": selection.get("manual_notes", ""),
        })

        for field, subdir in (
            ("figure_source", "figures"),
            ("data_source", "tables"),
            ("text_source", "notes"),
            ("tex_source", "tex/source"),
            ("provenance_source", "manifest/source"),
        ):
            raw_source = row.get(field, "").strip()
            if not raw_source:
                continue
            source = REPO_ROOT / raw_source
            destination = out / subdir / f"{candidate_id}__{source.name}"
            artifacts.append(copy_artifact(source, destination, out))

    tex_lines = [
        "% Generated by paper_evidence/scripts/build_release_package.py.",
        "% Edit this file only inside the release package and keep the manifest.",
        "\\graphicspath{{figures/}}",
        "",
    ]
    for candidate in candidates:
        candidate_id = candidate["candidate_id"]
        figure = next(
            item for item in artifacts
            if item["release_path"].startswith(f"figures/{candidate_id}__")
        )
        table = next(
            item for item in artifacts
            if item["release_path"].startswith(f"tables/{candidate_id}__")
        )
        figure_name = Path(figure["release_path"]).name
        table_name = Path(table["release_path"]).name
        tex_lines.extend([
            f"\\subsection{{{latex_text(candidate['title'])}}}",
            f"% Candidate {candidate_id} v{candidate['version']} status: {candidate['status']}",
            "% Replace this placeholder with reviewed manuscript prose.",
            f"Candidate status: \\texttt{{{latex_text(candidate['status'])}}}.\\\\",
            "",
            "\\begin{figure}[t]",
            "  \\centering",
            f"  \\includegraphics[width=\\linewidth]{{{figure_name}}}",
            f"  \\caption{{{latex_text(candidate['title'])}. Replace this caption after reviewing the claim matrix and source manifest.}}",
            f"  \\label{{fig:{candidate_id.lower()}}}",
            "\\end{figure}",
            "",
            f"Table~\\ref{{tab:{candidate_id.lower()}}} points to the compact source table \\texttt{{{latex_text(table_name)}}}; replace this placeholder with the reviewed tabular result.",
            "\\begin{table}[t]",
            "  \\centering",
            "  \\begin{tabular}{ll}",
            "    Candidate & Status \\\\",
            f"    {candidate_id} & \\texttt{{{latex_text(candidate['status'])}}} \\\\",
            "  \\end{tabular}",
            f"  \\caption{{Placeholder table for {latex_text(candidate['title'])}; populate from the release CSV after claim review.}}",
            f"  \\label{{tab:{candidate_id.lower()}}}",
            "\\end{table}",
            "",
        ])
    tex_path = out / "tex/evidence_bundle.tex"
    tex_path.parent.mkdir(parents=True, exist_ok=True)
    tex_path.write_text("\n".join(tex_lines) + "\n")

    manifest = {
        "release_id": args.release_id,
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "DRAFT",
        "scientific_policy": "Do not promote PROVENANCE_PARTIAL or UNVERIFIED candidates to final claims without closing gates.",
        "selection_file": str(selection_path.relative_to(REPO_ROOT)),
        "candidates": candidates,
        "artifacts": artifacts,
        "rebuild_command": "python paper_evidence/scripts/build_release_package.py --release-id <id> --selection paper_evidence/release_selection.tsv --out paper_evidence/releases/<id>",
        "overleaf": {
            "git_commit_or_version": "FILL_AFTER_OVERLEAF_SYNC",
            "compile_status": "NOT_CHECKED",
        },
    }
    manifest_path = out / "manifest/release_manifest.json"
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    shutil.copy2(
        REPO_ROOT / "paper_evidence/templates/CLAIM_EVIDENCE_MATRIX.tsv",
        out / "manifest/CLAIM_EVIDENCE_MATRIX.tsv",
    )
    shutil.copy2(
        REPO_ROOT / "paper_evidence/templates/overleaf_sync_checklist.md",
        out / "manifest/overleaf_sync_checklist.md",
    )
    (out / "README.md").write_text(
        f"# {args.release_id}\n\n"
        "This is a draft evidence package. Review the manifest, claim matrix, "
        "scientific status, and compiled TeX before using it in a manuscript.\n"
    )
    print(out)


if __name__ == "__main__":
    main()
