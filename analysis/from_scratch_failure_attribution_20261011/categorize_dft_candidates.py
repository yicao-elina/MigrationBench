#!/usr/bin/env python3
"""Categorize the 639 prepared DFT candidates and freeze wave 1 selection.

The candidate inventory is an evidence layer generated by the all-replicate
failure-attribution analysis.  This script does not alter that inventory or
submit work.  It adds a reproducible category/selection layer and chooses one
mechanism-focused wave of at most twenty structures.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results_all_replicates"
CANDIDATE_DIR = RESULTS / "dft_candidates_prepared_only"
CANDIDATE_MANIFEST = CANDIDATE_DIR / "manifest.csv"
FEATURES = RESULTS / "frame_features.csv"
RUN_SUMMARY = RESULTS / "run_summary.csv"
REMOTE_ROOT = "/scratch16/pclancy3/yi/mace_from_scratch_failure_attribution_20261011/results_all_replicates/dft_candidates_prepared_only"

SOURCE_ORDER = {"original": 0, "reproduce-1": 1, "reproduce-2": 2}
WINDOW_ORDER = {"stable_early": 0, "stable_pre": 1, "precursor": 2, "threshold": 3}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def choose_nearest_to(value: float, values: pd.Series) -> int:
    distances = (values.astype(float) - float(value)).abs()
    return int(distances.idxmin())


def main() -> None:
    candidates = pd.read_csv(CANDIDATE_MANIFEST).fillna("")
    features = pd.read_csv(FEATURES).fillna("")
    runs = pd.read_csv(RUN_SUMMARY).fillna("")
    if len(candidates) != 639:
        raise RuntimeError(f"expected 639 candidate rows, found {len(candidates)}")

    key = ["source", "training_seed", "window", "step"]
    feature_cols = [
        "trigger", "force_max_norm_eV_A", "rms_force_eV_A", "temperature_K",
        "min_distance_A", "outside_train_q99", "outside_train_q95",
        "distance_to_train", "distance_to_neb", "Cr_displacement_max_A",
        "Cr_velocity_max_A_ps", "Cr_kinetic_max_eV", "worst_force_atom_species",
        "top_force_min_neighbor_A", "top_force_n_neighbors_3p2",
    ]
    feature_view = features[key + [c for c in feature_cols if c in features.columns]].copy()
    if feature_view.duplicated(key).any():
        raise RuntimeError("frame_features has duplicate candidate keys")
    data = candidates.merge(feature_view, on=key, how="left", suffixes=("", "_feature"), validate="one_to_one")
    if data["trigger"].eq("").all():
        raise RuntimeError("candidate/frame merge did not recover trigger values")

    run_view = runs[["source", "training_seed", "status", "terminal", "onset_ps", "onset_step", "stop_reason"]].copy()
    data = data.merge(run_view, on=["source", "training_seed"], how="left", validate="many_to_one")
    data["run_key"] = data.apply(lambda row: f"{row.source}__seed{int(row.training_seed)}", axis=1)
    data["candidate_group"] = data["window"].map({
        "stable_early": "stable_early_control",
        "stable_pre": "stable_pre_onset",
        "precursor": "precursor_near_onset",
        "threshold": "threshold_or_terminal",
    })
    data.loc[(data["window"] == "threshold") & (data["trigger"] == "not_observed"), "candidate_group"] = "terminal_stable_target"
    if data["candidate_group"].isna().any():
        raise RuntimeError("unclassified candidate window")

    data["source_order"] = data["source"].map(SOURCE_ORDER)
    data["window_order"] = data["window"].map(WINDOW_ORDER)
    data["local_extxyz"] = data["prepared_extxyz"].map(lambda p: str(CANDIDATE_DIR / Path(str(p)).name))
    data["remote_extxyz"] = data["prepared_extxyz"]
    data["local_extxyz_sha256"] = [sha256(Path(path)) for path in data["local_extxyz"]]
    if not all(Path(path).is_file() for path in data["local_extxyz"]):
        raise RuntimeError("one or more local candidate extxyz files are missing")

    data = data.sort_values(["source_order", "training_seed", "step", "window_order", "prepared_extxyz"]).reset_index(drop=True)
    data.insert(0, "candidate_id", [f"dftcand_{i:04d}" for i in range(1, len(data) + 1)])
    data["batch_id"] = "unassigned"
    data["selection_role"] = "not_selected"
    data["selection_reason"] = "pending_wave_selection"

    selected: list[int] = []

    # Every threshold/terminal row is retained in wave 1.  This is eight
    # rows: seven operational threshold crossings plus the 1000 ps target
    # completion that must remain a negative control.
    threshold = data.index[data["window"].eq("threshold")].tolist()
    selected.extend(threshold)
    data.loc[threshold, "selection_role"] = data.loc[threshold, "candidate_group"].map({
        "threshold_or_terminal": "threshold_or_terminal",
        "terminal_stable_target": "terminal_stable_target",
    })
    data.loc[threshold, "selection_reason"] = "all threshold-or-terminal rows retained to cover every run"

    # One precursor closest to the operational onset per run.  For the run
    # that reached 1000 ps, this deterministically becomes the latest sampled
    # precursor frame and serves as a late stable/near-onset negative control.
    for run_key, group in data[data["window"].eq("precursor")].groupby("run_key", sort=True):
        idx = group["step"].astype(int).idxmax()
        selected.append(int(idx))
        data.loc[idx, "selection_role"] = "precursor_near_onset"
        data.loc[idx, "selection_reason"] = "latest precursor frame for this run; closest sampled frame before/at terminal boundary"

    # Three early stable controls, one for each training-model hash, keep the
    # first wave balanced across the model family without spending the whole
    # wave on near-failure frames.
    stable = data[(data["source"] == "original") & data["window"].eq("stable_early")]
    for seed in sorted(stable["training_seed"].astype(int).unique()):
        group = stable[stable["training_seed"].astype(int).eq(seed)]
        idx = choose_nearest_to(10000, group["step"])
        selected.append(idx)
        data.loc[idx, "selection_role"] = "stable_early_model_control"
        data.loc[idx, "selection_reason"] = "10 ps early-stable control for one of the three training-model hashes"

    selected = sorted(set(selected))
    if len(selected) != 20:
        raise RuntimeError(f"wave 1 must contain exactly 20 unique candidates, found {len(selected)}")
    selected_ids = set(data.loc[selected, "candidate_id"])
    data.loc[data["candidate_id"].isin(selected_ids), "batch_id"] = "wave_01"
    data.loc[data["batch_id"].eq("wave_01"), "selection_reason"] = data.loc[data["batch_id"].eq("wave_01"), "selection_reason"].astype(str)
    data["submitted"] = False
    data["dft_status"] = data["batch_id"].map({"wave_01": "selected_wave_01", "unassigned": "prepared_only"})

    # Stable machine-readable order and compact summaries.
    data["batch_order"] = data["batch_id"].map({"wave_01": 0, "unassigned": 1}).fillna(9)
    data = data.sort_values(["batch_order", "source_order", "training_seed", "step", "window_order", "candidate_id"]).reset_index(drop=True)
    data.to_csv(ROOT / "candidate_categorization.csv", index=False)
    data[data["batch_id"].eq("wave_01")].to_csv(ROOT / "wave_01_manifest.csv", index=False)
    summary = data.groupby(["candidate_group", "source", "training_seed"], dropna=False).size().reset_index(name="n_candidates")
    summary.to_csv(ROOT / "candidate_category_summary.csv", index=False)
    wave = data[data["batch_id"].eq("wave_01")].copy()
    wave_summary = wave.groupby(["selection_role", "source", "training_seed"], dropna=False).size().reset_index(name="n_selected")
    wave_summary.to_csv(ROOT / "wave_01_selection_summary.csv", index=False)

    payload = {
        "schema_version": 1,
        "inventory": 639,
        "inventory_manifest": str(CANDIDATE_MANIFEST),
        "local_candidate_dir": str(CANDIDATE_DIR),
        "remote_candidate_dir": REMOTE_ROOT,
        "categories": data["candidate_group"].value_counts().sort_index().to_dict(),
        "wave_01_size": len(selected),
        "wave_01_roles": wave["selection_role"].value_counts().sort_index().to_dict(),
        "selection_rule": {
            "threshold_or_terminal": "all threshold window rows, including the 1000 ps not_observed terminal control",
            "precursor_near_onset": "latest precursor row per source/training_seed run",
            "stable_early_model_control": "10 ps stable_early row from original source for each training seed",
        },
        "dft_submission_status": "not_submitted_by_this_script",
    }
    (ROOT / "candidate_categorization.json").write_text(json.dumps(payload, indent=2) + "\n")

    print(json.dumps(payload, indent=2))
    print("\nwave_01 candidates:")
    cols = ["candidate_id", "source", "training_seed", "window", "time_ps", "candidate_group", "selection_role", "trigger", "force_max_norm_eV_A", "temperature_K", "min_distance_A", "distance_to_train", "local_extxyz_sha256"]
    print(wave[cols].to_string(index=False))


if __name__ == "__main__":
    main()
