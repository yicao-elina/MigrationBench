#!/usr/bin/env python3
"""Write OVERVIEW.md and OVERVIEW.xlsx: the master tables, how data is aggregated, every figure
and table, and where each layer of computed data lives. Reads the SQL registry only, so run
build_index.py (and check_sql.py) first.
"""
from __future__ import annotations

import re
import sqlite3
from collections import Counter

from overview_spec import LAYERS, LEGACY_TABLES, MASTER_FILES, OTHER_TABLES, tiers
from path_roots import PACKAGE, REPO

DB = REPO / "analysis/migrationbench_asset_registry_20261025/migrationbench_asset_registry.sqlite"
MODEL_FAMILIES = [("FT", r"\bFT|fine-tun"), ("Scratch", r"scratch"), ("Foundation", r"foundation|MPA-?0|MP-0b3|OMAT")]


def rows(conn, query: str) -> list[dict]:
    cursor = conn.execute(query)
    names = [c[0] for c in cursor.description]
    return [dict(zip(names, r)) for r in cursor]


def md_table(header: list[str], body: list[list]) -> list[str]:
    clean = lambda v: str(v if v is not None else "").replace("|", "\\|").replace("\n", " ")  # noqa: E731
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header),
            *("| " + " | ".join(clean(v) for v in row) + " |" for row in body), ""]


SECTION_ORDER = ["main", "si", "response"]


def summary(panels: list[dict], width: int = 120) -> str:
    if len(panels) == 1:
        text = panels[0]["content"]
    else:
        text = "; ".join(f"({p['panel']}) {p['content']}" for p in panels)
    return text if len(text) <= width else text[: width - 1].rstrip() + "…"


def item_layers(conn) -> list[dict]:
    """One row per figure/table: the computed-data layers it rests on and where each lives."""
    out = []
    items = rows(conn, "SELECT i.*, l.* FROM rev1_items i JOIN rev1_item_calc_layers l USING (item_id) ORDER BY i.rowid")
    for item in sorted(items, key=lambda i: SECTION_ORDER.index(i["section"])):
        panels = rows(conn, f"SELECT * FROM rev1_results_index WHERE item_id = '{item['item_id']}'")
        column = lambda *names: " ".join(p[n] for p in panels for n in names)  # noqa: E731
        out.append({
            "section": item["section"], "item": item["item_id"], "title": summary(panels),
            "panels": item["panels"], "L0": item["L0_reference"], "L1": item["L1_split_models"],
            "L2": item["L2_mlip_sims"], "L3": item["L3_derived"], "L5": item["L5_kind"],
            "raw at": tiers(column("raw_location", "models")),
            "derived + plotted at": tiers(column("upstream_data", "plotted_data")),
            "generator at": tiers(column("generator", "final_asset")),
            "status": item["statuses"], "folder": item["item_dir"],
        })
    return out


def sql_catalog(conn) -> list[list]:
    out = []
    described = {table: purpose for _f, table, _row, purpose in MASTER_FILES}
    for (name, kind) in conn.execute("SELECT name, type FROM sqlite_master WHERE type IN ('table','view') "
                                     "AND name NOT LIKE 'sqlite_%' ORDER BY type, name"):
        count = conn.execute(f'SELECT COUNT(*) FROM "{name}"').fetchone()[0]
        group = "Revision 1 trace" if name.startswith(("rev1_", "v_rev1_")) else "2026-10-25 registry"
        purpose = described.get(name) or OTHER_TABLES.get(name) or LEGACY_TABLES.get(name, "")
        out.append([group, kind, name, count, purpose[:110]])
    return sorted(out, key=lambda row: (row[0] != "Revision 1 trace", row[1], row[2]))


def build_markdown(conn) -> str:
    counts = {t: conn.execute(f'SELECT COUNT(*) FROM "{t}"').fetchone()[0] for _f, t, *_ in MASTER_FILES}
    layers = item_layers(conn)
    lines = ["# Revision 1 trace overview", "",
             "Generated by `tools/build_overview.py` from the SQL registry; do not hand-edit. "
             "Same content, unabridged, in `OVERVIEW.xlsx`.", ""]
    lines += ["## 1. Master tables", ""]
    lines += md_table(["File", "SQL table", "Rows", "One row is", "Purpose"],
                      [[f"`{f}`", f"`{t}`", counts[t], row, purpose] for f, t, row, purpose in MASTER_FILES])
    lines += ["## 2. How the data is aggregated", "",
              "1. **Survey → sources.** Surveys of the repo, the ChatGPT workspace, ~/Downloads, Remotion and "
              "Rockfish are recorded in `sources/*.tsv` (one row per panel/table, per Rockfish directory, per "
              "checkpoint). Fixes made after the survey go in `sources/status_overrides.tsv`.",
              "2. **Import.** `tools/import_external.py` copies what the trace needs into the repo per "
              "`imports/import_plan.tsv`; heavy binaries go to the archive store. Every file is logged with sha256.",
              "3. **Build.** `tools/build_index.py` joins sources, overrides and manifests into the master TSVs, the "
              "per-item `PROVENANCE.md` pages and migration `002` of the SQL registry. All paths are written "
              "portably (table below).",
              "4. **Legacy registry.** `tools/clean_legacy_registry.py` (migration `003`) makes the 2026-10-25 "
              "registry tables portable too.",
              "5. **Check.** `tools/verify_trace.py` (paths, sha256), `tools/check_sql.py` (integrity, keys, row "
              "counts), `tools/verify_table_rounding.py` (hand-rounded tables), `tests/`.", ""]
    lines += md_table(["Path label", "Resolves to", "Host", "Meaning"],
                      [[f"`{r['label']}:`", r["absolute_root"] or "—", r["host"], r["meaning"]]
                       for r in rows(conn, "SELECT * FROM rev1_path_roots")])
    lines += ["## 3. Every figure and table", ""]
    lines += md_table(["Section", "Item", "Panels / label", "Content", "Status", "Folder"],
                      [[r["section"], r["item"], r["panels"], r["title"], r["status"], f"`{r['folder']}`"]
                       for r in layers])
    lines += ["## 4. Reproduction script and evidence per item", "",
              "Each item has a script under its folder's `source/` that regenerates it from repo data and writes "
              "`evidence/*.json` (inputs and outputs with sha256, the comparison with the submitted version, "
              "a hardcoding lint). `tools/verify_reproducibility.py` checks that the evidence is current; "
              "`--rerun` regenerates everything first.", ""]
    lines += md_table(["Item", "Result", "Script(s)", "Checks", "Inputs", "Notes"],
                      [[r["item_id"], r["result"], " ".join(f"`{s}`" for s in r["scripts"].split()), r["checks"],
                        r["inputs"], r["problems"][:160]]
                       for r in rows(conn, "SELECT * FROM rev1_reproducibility")])
    lines += ["## 5. Layers of computed data behind each item", "",
              "Layers, curated per item in `sources/item_calc_layers.tsv` (SQL `rev1_item_calc_layers`):", ""]
    lines += md_table(["Layer", "Holds"], [[code, meaning] for code, _col, meaning in LAYERS])
    lines += ["L4 (plotted data) for each panel is the `plotted_data` column of `RESULTS_INDEX.tsv`.", "",
              "### 5a. What each item rests on", ""]
    lines += md_table(["Item", "L0 reference", "L1 split / models", "L2 MLIP simulations", "L3 derived", "L5"],
                      [[r["item"], r["L0"], r["L1"], r["L2"], r["L3"], r["L5"]] for r in layers])
    lines += ["### 5b. Where each layer is stored", "",
              "Read from the paths each item cites. *git* = this repository; *archive store* = "
              "`archive:` (laptop, to back up to Skipjack); *Rockfish* = `rockfish:` (to migrate to Skipjack); "
              "*Canva* = composed in Canva design `DAHZXpLtN6U`.", ""]
    lines += md_table(["Item", "L0-L2 raw outputs + models", "L3-L4 derived + plotted data", "L5 generator + final"],
                      [[r["item"], r["raw at"], r["derived + plotted at"], r["generator at"]] for r in layers])
    lines += ["## 6. Pipeline stages", ""]
    lines += md_table(["#", "Stage", "Feeds"], [[r["stage"], r["stage_name"], r["feeds"]]
                                              for r in rows(conn, "SELECT * FROM rev1_pipeline_stages")])
    lines += ["## 7. Models", ""]
    lines += md_table(["Family", "Used in paper", "Checkpoints", "sha256 verified on Rockfish"],
                      [[r["family"], r["used_in_paper"], r["n"], r["ok"]] for r in rows(conn, """
        SELECT family, used_in_paper, COUNT(*) n, SUM(sha256_verified = 'OK') ok FROM rev1_model_registry
        GROUP BY 1, 2 ORDER BY 1, 2""")])
    lines += ["## 8. Raw-data storage and migration", ""]
    lines += md_table(["Host", "Migrate to", "Locations"], [[r["host"], r["migrate_to"], r["n"]] for r in rows(conn, """
        SELECT host, migrate_to, COUNT(*) n FROM rev1_storage_locations GROUP BY 1, 2 ORDER BY 1, 2""")])
    plan = Counter((r["priority"], r["used_in_paper"]) for r in rows(conn, "SELECT * FROM rev1_rockfish_migration_plan"))
    lines += md_table(["Rockfish priority", "Used in paper", "Directories"],
                      [[p, u, n] for (p, u), n in sorted(plan.items())])
    lines += ["## 9. Open issues", ""]
    lines += md_table(["#", "Group", "Issue"], [[r["issue_no"], r["issue_group"], r["title"]]
                                              for r in rows(conn, "SELECT * FROM v_rev1_open_issues")])
    lines += ["## 10. SQL registry contents", "",
              f"`{DB.relative_to(REPO)}`; check with `python3 {PACKAGE.relative_to(REPO)}/tools/check_sql.py`.", ""]
    lines += md_table(["Group", "Type", "Name", "Rows", "Holds"], sql_catalog(conn))
    return "\n".join(lines)


def build_workbook(conn, path) -> None:
    from openpyxl import Workbook
    from openpyxl.styles import Font
    from openpyxl.utils import get_column_letter

    book = Workbook()
    book.remove(book.active)
    sheets = {
        "Items": item_layers(conn),
        "Panels": rows(conn, "SELECT * FROM rev1_results_index"),
        "Pipeline": rows(conn, "SELECT * FROM rev1_pipeline_stages"),
        "Models": rows(conn, "SELECT * FROM rev1_model_registry"),
        "Storage": rows(conn, "SELECT * FROM rev1_storage_locations"),
        "RockfishPlan": rows(conn, "SELECT * FROM rev1_rockfish_migration_plan"),
        "KnownIssues": rows(conn, "SELECT * FROM rev1_known_issues"),
        "PathRoots": rows(conn, "SELECT * FROM rev1_path_roots"),
        "Reproducibility": rows(conn, "SELECT * FROM rev1_reproducibility"),
        "SQLTables": [dict(zip(["group", "type", "name", "rows", "holds"], r)) for r in sql_catalog(conn)],
    }
    for name, data in sheets.items():
        sheet = book.create_sheet(name)
        header = list(data[0]) if data else []
        sheet.append(header)
        for cell in sheet[1]:
            cell.font = Font(bold=True)
        for row in data:
            sheet.append([row[h] for h in header])
        sheet.freeze_panes = "A2"
        for index, column in enumerate(header, start=1):
            width = max([len(str(column))] + [min(len(str(r[column] or "")), 60) for r in data[:200]])
            sheet.column_dimensions[get_column_letter(index)].width = width + 2
    book.save(path)


def main() -> int:
    conn = sqlite3.connect(DB)
    (PACKAGE / "OVERVIEW.md").write_text(build_markdown(conn) + "\n")
    build_workbook(conn, PACKAGE / "OVERVIEW.xlsx")
    print(f"wrote {PACKAGE.relative_to(REPO)}/OVERVIEW.md and OVERVIEW.xlsx; {len(LAYERS)} data layers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
