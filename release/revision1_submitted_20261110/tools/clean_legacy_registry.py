#!/usr/bin/env python3
"""Make the pre-Revision-1 registry tables portable (migration 003).

The 2026-10-25 registry and the 2026-11-01 Canva migration recorded absolute laptop
paths (Codex worktrees, the ChatGPT workspace, ~/Downloads, Google Drive). This script
rewrites them with the same rules as the Revision 1 index (path_roots.localize): imported
files point at their repo copy, archived Downloads files at archive:downloads_20261110/,
everything else at a `<label>:` root listed in rev1_path_roots.

Outputs:
  analysis/migrationbench_asset_registry_20261025/migrations/003_portable_paths_legacy_tables.sql
  imports/LEGACY_REGISTRY_PATH_REWRITES.tsv   one row per rewritten cell, with whether the target exists
Run with --apply to execute the migration (it is idempotent: a second run finds nothing to change).
"""
from __future__ import annotations

import argparse
import csv
import sqlite3
import subprocess
from datetime import date

from path_roots import PACKAGE, REPO, import_rewrites, localize, resolve
from sql_tables import sql_literal

REGISTRY = REPO / "analysis/migrationbench_asset_registry_20261025"
DB = REGISTRY / "migrationbench_asset_registry.sqlite"
MIGRATION = REGISTRY / "migrations/003_portable_paths_legacy_tables.sql"
REPORT = PACKAGE / "imports/LEGACY_REGISTRY_PATH_REWRITES.tsv"
TRIPTYCH = "analysis/neb_cross_element_triptychs_20261024"
FIG2_V16 = "docs/reproducibility/canva_figure_provenance/R03_typography18pt/figures/figure02_temperature_reference_layout_v16/"
# Cells whose recorded location no longer exists, with the evidence for the replacement.
LEGACY_FIXES = [
    (FIG2_V16, f"git:b2924bc^:{FIG2_V16}",
     "superseded Fig. 2 v16 outputs removed in b2924bc; still in history"),
    (f"{TRIPTYCH}/archive/legacy_figure_products_20261024",
     f"{TRIPTYCH}/foundation_self_relaxed_4x3_20261024/archive/legacy_figure_products_20261024",
     "registry omitted the foundation_self_relaxed_4x3_20261024/ level"),
    ("downloads:foundation_model_class_3x3_R03.pdf",
     f"{TRIPTYCH}/foundation_self_relaxed_4x3_20261024/archive/legacy_figure_products_20261024/figures/"
     "foundation_class_3x3_R03/foundation_model_class_3x3_R03.pdf",
     "repo copy has the recorded sha256 59d62024"),
]
PATH_COLUMNS = {"source_path", "local_path", "asset_path", "manifest_path", "campaign_path", "artifact_path"}


def target_status(value: str) -> str:
    """Where a rewritten single-path cell now points, and whether it exists."""
    value = value.split(":", 1)[1] if value.startswith("external:") else value
    if value.startswith("git:"):
        spec = value.removeprefix("git:")
        found = subprocess.run(["git", "-C", str(REPO), "cat-file", "-e", spec], capture_output=True).returncode == 0
        return "exists (git history)" if found else "missing (git history)"
    if ":" in value.split("/")[0]:
        local = resolve(value)
        if local is None:
            return "remote"
        return "exists" if local.exists() else "missing (outside repo)"
    return "exists" if (REPO / value).exists() else "missing (repo path)"


def fix(value: str) -> tuple[str, str]:
    reasons = []
    for old, new, why in LEGACY_FIXES:
        if old in value and new not in value:
            value, reasons = value.replace(old, new), reasons + [why]
    return value, "; ".join(reasons) or "portable path rewrite"


def legacy_tables(conn: sqlite3.Connection) -> list[str]:
    names = conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'rev1_%' "
                         "AND name NOT LIKE 'sqlite_%' ORDER BY name")
    return [name for (name,) in names]


def changes(conn: sqlite3.Connection) -> list[dict]:
    rules, found = import_rewrites(), []
    for table in legacy_tables(conn):
        columns = [row[1] for row in conn.execute(f'PRAGMA table_info("{table}")') if row[2].upper() in {"TEXT", ""}]
        for column in columns:
            query = f'SELECT rowid, "{column}" FROM "{table}" WHERE "{column}" LIKE \'%/Users/%\' OR "{column}" LIKE \'%~/Downloads%\''
            for rowid, value in conn.execute(query):
                new, reason = fix(localize(value, rules))
                if new != value:
                    found.append({"table": table, "column": column, "rowid": rowid, "old": value, "new": new,
                                  "target": target_status(new) if column in PATH_COLUMNS else "text",
                                  "reason": reason})
    return found


def migration_sql(found: list[dict]) -> str:
    out = ["-- Generated by release/revision1_submitted_20261110/tools/clean_legacy_registry.py; do not hand-edit.",
           "-- Rewrites absolute laptop paths in the pre-Revision-1 tables to portable paths (see rev1_path_roots).",
           "BEGIN;"]
    for row in found:
        out.append(f'UPDATE "{row["table"]}" SET "{row["column"]}" = {sql_literal(row["new"], True)} '
                   f'WHERE rowid = {row["rowid"]} AND "{row["column"]}" = {sql_literal(row["old"], True)};')
    summary = f"{len(found)} cells rewritten; per-cell list in {REPORT.relative_to(REPO)}"
    out.append("INSERT INTO audit_log (checked_at, check_name, result, details) VALUES "
               f"({sql_literal(date.today().isoformat())}, 'portable_paths_003', 'APPLIED', {sql_literal(summary, True)});")
    out.append("INSERT OR REPLACE INTO metadata (key, value) VALUES ('portable_paths_migration', "
               "'003_portable_paths_legacy_tables.sql');")
    out.append("COMMIT;")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--apply", action="store_true", help="execute the migration on the SQLite registry")
    args = parser.parse_args()
    with sqlite3.connect(DB) as conn:
        found = changes(conn)
        if not found:
            print("legacy tables already portable; nothing to do")
            return 0
        with REPORT.open("w", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(found[0]), delimiter="\t", lineterminator="\n")
            writer.writeheader()
            writer.writerows(found)
        MIGRATION.write_text(migration_sql(found))
        if args.apply:
            conn.executescript(MIGRATION.read_text())
    missing = [row for row in found if row["target"].startswith("missing")]
    print(f"{len(found)} cells to rewrite, {len(missing)} point at missing files; "
          f"{'applied' if args.apply else 'dry run'} -> {MIGRATION.relative_to(REPO)}")
    for row in missing:
        print(f"  {row['target']}: {row['table']}.{row['column']} -> {row['new']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
