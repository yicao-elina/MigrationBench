#!/usr/bin/env python3
"""Write the Rockfish -> Skipjack migration plan and rsync commands (nothing is executed).

Reads STORAGE_LOCATIONS.tsv and keeps rockfish rows whose ``migrate_to`` is not
"do not migrate". Rows are ordered by priority (paper-used first). For each
row it writes one rsync command that copies into ``$SKIPJACK_ARCHIVE/<proposed
archive path>`` and excludes regenerable heavy files (QE wavefunctions, .save
and mixing scratch, per-epoch training checkpoints).

Outputs:
  ROCKFISH_MIGRATION_PLAN.tsv
  tools/rockfish_to_skipjack_rsync.sh   (run on Rockfish by hand, after review)
"""
from __future__ import annotations

import csv
import re
import shlex
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
PRIORITY = {"yes": 1, "partial": 2, "no/unused-but-keep": 3}
EXCLUDES = ["wfc*.dat", "*.wfc*", "*.save/", "*.mix*", "charge-density.dat", "*_epoch-*.pt", "core.*"]
FIELDS = ["priority", "used_in_paper", "rockfish_path", "size", "category", "paper_items",
          "skipjack_target", "local_copy", "notes"]


CATEGORY_DIRS = {"training_data": "training_data", "model": "models", "DFT": "dft", "AIMD": "aimd",
                 "MD": "md", "NEB": "neb", "sliding": "sliding", "analysis": "analysis", "legacy": "legacy"}


def clean_target(proposed: str, category: str, source: str) -> str:
    """migrationbench_archive/<category dir>/<source basename>: unique and free of prose."""
    match = re.search(r"migrationbench_archive/[\w./-]+", proposed or "")
    if match:
        base = match.group(0).rstrip("/")
    else:
        first = category.split("+")[0]
        base = "migrationbench_archive/" + CATEGORY_DIRS.get(first, "unsorted")
    name = Path(source.rstrip("/")).name
    return base if base.endswith("/" + name) else f"{base}/{name}"


def plan_rows() -> list[dict]:
    with (PACKAGE / "STORAGE_LOCATIONS.tsv").open() as handle:
        rows = [r for r in csv.DictReader(handle, delimiter="\t")
                if r["host"] == "rockfish" and r["migrate_to"] != "do not migrate"
                and r["used_in_paper"] in PRIORITY]
    plan = []
    for row in rows:
        path = row["location"].removeprefix("rockfish:")
        target = clean_target(row["proposed_archive_path"], row["category"], path)
        plan.append({"priority": PRIORITY[row["used_in_paper"]], "used_in_paper": row["used_in_paper"],
                     "rockfish_path": path, "size": row["size"], "category": row["category"],
                     "paper_items": row["paper_items"], "skipjack_target": target.lstrip("/"),
                     "local_copy": row["local_copy"], "notes": row["notes"]})
    return sorted(plan, key=lambda r: (r["priority"], r["category"], r["rockfish_path"]))


def rsync_script(plan: list[dict]) -> str:
    excludes = " ".join(f"--exclude={shlex.quote(e)}" for e in EXCLUDES)
    lines = ["#!/usr/bin/env bash",
             "# Generated by tools/plan_rockfish_migration.py. Review ROCKFISH_MIGRATION_PLAN.tsv first.",
             "# Usage on Rockfish:  SKIPJACK_ARCHIVE=user@skipjack:/path/to/migrationbench_archive \\",
             "#                     bash rockfish_to_skipjack_rsync.sh [--dry-run]",
             "set -euo pipefail",
             ': "${SKIPJACK_ARCHIVE:?set SKIPJACK_ARCHIVE to the skipjack destination}"',
             'EXTRA="${1:-}"', ""]
    for row in plan:
        source = shlex.quote(row["rockfish_path"].rstrip("/") + "/")
        target = '"$SKIPJACK_ARCHIVE"/' + shlex.quote(row["skipjack_target"].rstrip("/") + "/")
        lines.append(f"# P{row['priority']} {row['category']} {row['size']} {row['paper_items'][:80]}")
        lines.append(f"rsync -a --partial --mkpath $EXTRA {excludes} {source} {target}")
    return "\n".join(lines) + "\n"


def main() -> int:
    plan = plan_rows()
    with (PACKAGE / "ROCKFISH_MIGRATION_PLAN.tsv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(plan)
    script = PACKAGE / "tools/rockfish_to_skipjack_rsync.sh"
    script.write_text(rsync_script(plan))
    counts = {p: sum(1 for r in plan if r["priority"] == p) for p in (1, 2, 3)}
    print(f"{len(plan)} directories to migrate (P1 paper-used {counts[1]}, P2 partial {counts[2]}, "
          f"P3 keep {counts[3]}); wrote {script.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
