from __future__ import annotations

import csv
from pathlib import Path


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def pick(records: list[dict[str, str]], **criteria: str) -> dict[str, str]:
    for record in records:
        if all(record.get(key) == value for key, value in criteria.items()):
            return record
    raise ValueError(f"no row matches {criteria}")


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    data = root / "data" / "processed"
    dft = pick(rows(data / "dft_neb_barriers.csv"), path="1-4")
    shap = pick(rows(data / "shap_surrogate_r2_revised.csv"), model="FT - 600K")
    md = pick(rows(data / "md_transport_metrics.csv"), model="FT-MultiT")
    barrier = dft.get("barrier_eV") or dft.get("barrier_ev")
    r2 = shap.get("r2_5fold_cv")
    diffusion = md.get("D_block_mean_cm2_s")
    if not all((barrier, r2, diffusion)):
        raise ValueError("canonical result columns are missing")
    output = root / "paper" / "results_generated.tex"
    output.write_text(
        "% Generated by scripts/generate_results_tex.py; do not edit.\n"
        f"\\newcommand{{\\DFTNEBOneFourBarrier}}{{{float(barrier):.3f}}}\n"
        f"\\newcommand{{\\SHAPFTSixHundredKCV}}{{{float(r2):.4f}}}\n"
        f"\\newcommand{{\\MDFTMultiTDiffusion}}{{{float(diffusion):.3e}}}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()

