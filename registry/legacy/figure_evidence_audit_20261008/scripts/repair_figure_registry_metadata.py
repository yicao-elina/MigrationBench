#!/usr/bin/env python3
"""Refresh generated evidence metadata without touching authored figure prose."""

from __future__ import annotations

import csv
import json
from pathlib import Path

import yaml


MAIN = Path("/Users/alina/Documents/ChatGPT/Wiley-MigrationBench")
AUDIT = MAIN / "analysis/figure_evidence_audit_20261008"
PAPER = Path("/Users/alina/Project/migrationbench-paper-repro/paper/revision1")
REGISTRY = PAPER / "figure_registry"
FIGURES = REGISTRY / "figures"


def load_matrix() -> dict[str, dict]:
    matrix: dict[str, dict] = {}
    with (AUDIT / "figure_evidence_matrix.tsv").open(encoding="utf-8") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            matrix[row["logical_figure"]] = row
            matrix[row["logical_path"]] = row
    return matrix


def load_table_packages() -> dict[str, dict]:
    packages: dict[str, dict] = {}
    root = AUDIT / "generated/table_backed_packages"
    for path in root.glob("*/evidence_package_manifest.json"):
        data = json.loads(path.read_text(encoding="utf-8"))
        data["_manifest_path"] = str(path)
        packages[data["package_id"]] = data
    return packages


def source_candidates(row: dict) -> dict[str, list[str]]:
    return {
        key: [item.strip() for item in row.get(key, "").split(" | ") if item.strip()]
        for key in (
            "caption_discussion_source_candidates",
            "raw_or_processed_data_candidates",
            "plot_script_candidates",
        )
    }


def package_candidates(package: dict) -> dict[str, list[str]]:
    source = [item["path"] for item in package.get("source_files", [])]
    processed = [item["path"] for item in package.get("processed_files", [])]
    caption = [str(Path(package["_manifest_path"]).with_name("caption_results_discussion.md"))]
    scripts = [package.get("generated_by", ""), package.get("plot_atlas_root", "")]
    return {
        "caption_discussion_source_candidates": [item for item in caption if item],
        "raw_or_processed_data_candidates": source + processed,
        "plot_script_candidates": [item for item in scripts if item],
    }


def write_auto_tex(path: Path, candidates: dict[str, list[str]]) -> None:
    labels = {
        "caption_discussion_source_candidates": "Caption/discussion source",
        "raw_or_processed_data_candidates": "Raw or processed data",
        "plot_script_candidates": "Plot or processing script",
    }
    lines = [
        r"\emph{Machine-collected evidence candidates (generated from the audit matrix; do not edit this file).}",
        r"\begin{itemize}[leftmargin=1.4em,noitemsep]",
    ]
    for key, label in labels.items():
        values = candidates.get(key, [])
        if values:
            for value in values:
                lines.append(rf"\item \textbf{{{label}:}} \url{{{value}}}")
        else:
            lines.append(rf"\item \textbf{{{label}:}} not identified in the audit matrix.")
    lines.append(r"\end{itemize}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    matrix = load_matrix()
    packages = load_table_packages()
    updated = 0
    skipped_locked = []
    missing = []
    for manifest_path in sorted(FIGURES.glob("FIG-*/manifest.yaml")):
        data = yaml.safe_load(manifest_path.read_text(encoding="utf-8")) or {}
        if data.get("lock_status") in {"locked", "promoted"}:
            skipped_locked.append(data.get("figure_id", manifest_path.parent.name))
            continue
        row = matrix.get(data.get("logical_figure"))
        package = packages.get(str(data.get("logical_figure", "")).split("/", 1)[-1])
        if row:
            candidates = source_candidates(row)
            metadata_source = str(AUDIT / "figure_evidence_matrix.tsv")
        elif package:
            candidates = package_candidates(package)
            metadata_source = package["_manifest_path"]
        else:
            missing.append(data.get("figure_id", manifest_path.parent.name))
            candidates = source_candidates({})
            metadata_source = str(AUDIT / "figure_evidence_matrix.tsv")
        data["evidence_candidates"] = candidates
        data["evidence_metadata_source"] = metadata_source
        manifest_path.write_text(yaml.safe_dump(data, sort_keys=False, allow_unicode=True), encoding="utf-8")
        write_auto_tex(manifest_path.parent / "evidence_auto.tex", candidates)
        page_path = manifest_path.parent / "page.tex"
        page_text = page_path.read_text(encoding="utf-8")
        auto_input = f"\\input{{figure_registry/figures/{data['figure_id']}/evidence_auto.tex}}"
        if auto_input not in page_text:
            marker = f"\\input{{figure_registry/figures/{data['figure_id']}/evidence.tex}}"
            page_text = page_text.replace(marker, marker + "\n" + auto_input, 1)
            page_path.write_text(page_text, encoding="utf-8")
        (manifest_path.parent / "evidence.md").write_text(
            "# Evidence candidates (generated)\n\n"
            + "\n".join(
                f"## {key}\n\n" + ("\n".join(f"- `{value}`" for value in values) if values else "- Not identified in the audit matrix.")
                for key, values in candidates.items()
            )
            + "\n",
            encoding="utf-8",
        )
        updated += 1
    if missing:
        raise SystemExit(f"updated {updated}; no audit-matrix match for: {', '.join(missing)}")
    suffix = f"; skipped locked/promoted: {', '.join(skipped_locked)}" if skipped_locked else ""
    print(f"refreshed generated evidence metadata for {updated} figure registries{suffix}")


if __name__ == "__main__":
    main()
